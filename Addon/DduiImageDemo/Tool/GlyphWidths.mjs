/**
 * Generates Source/GlyphWidths.js: the characters of the Bedrock client's
 * large bitmap font and their advance widths, and the advance width of every
 * Basic Multilingual Plane character in its smaller Unicode font, in font
 * pixels. A line whose characters are all in the large font is drawn in it;
 * any other character switches the whole line to the Unicode font. The large
 * font's character-to-cell table is read from the client executable, its
 * glyphs from default8.png, default8_1.png and default8_2.png, and the
 * Unicode font's from the glyph_XX.png pages.
 *
 * Usage: node Tool/GlyphWidths.mjs [font.brarchive path] [Minecraft.Windows.exe path]
 *
 * @module @sorrell/ddui-image-demo/Tool/GlyphWidths
 *
 * @file      GlyphWidths.mjs
 * @author    Gage Sorrell <gage@sorrell.sh>
 * @copyright (c) 2026 Gage Sorrell
 * @license   MIT
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
    ClientExecutable,
    FindClient,
    FontArchive,
    OpaqueColumns,
    ReadArchive,
    ReadLargeFontTable,
    SheetReader,
    UnicodePageName
} from "./ClientFont.mjs";

const Root = fileURLToPath(new URL("../", import.meta.url));

const Client = process.argv[2] && process.argv[3] ? undefined : FindClient();
const Files = ReadArchive(process.argv[2] ?? FontArchive(Client));
const LargeTable = ReadLargeFontTable(process.argv[3] ?? ClientExecutable(Client));
const Sheet = SheetReader(Files);

// notfound.png is drawn in place of a missing glyph, scaled to the 8-pixel cell height.
const NotFound = Sheet("notfound.png");
const NotFoundColumns = OpaqueColumns(NotFound, 0, NotFound.width);
const MissingWidth = Math.round((NotFoundColumns.Right - NotFoundColumns.Left + 1) * 8 / NotFound.width) + 1;

/**
 * Measures one large-font cell in font pixels, including the 1-pixel gap
 * after it. The three sheets hold 160 cells each, 8 by 12 pixels, with glyphs
 * drawn from their left edge; a space is 4 pixels and an empty cell is missing.
 *
 * @category Tool
 * @since 1.1.36
 */
function MeasureLarge(Code, Cell)
{
    if (Code === 0x20) return 4;
    const Columns = OpaqueColumns(Sheet([ "default8.png", "default8_1.png", "default8_2.png" ][Math.floor(Cell / 160)]), Cell % 160, 8, 12);
    return Columns ? Columns.Right + 2 : MissingWidth;
}

/**
 * Measures one character of the Unicode font in font pixels, including the
 * 1-pixel gap after it: its glyph page is drawn at half resolution, a space
 * is 4 pixels as in the large font, and a character without a glyph is missing.
 *
 * @category Tool
 * @since 1.1.36
 */
function MeasureSmall(CodePoint)
{
    if (CodePoint === 0x20) return 4;
    const Page = Sheet(UnicodePageName(CodePoint));
    const Columns = Page && OpaqueColumns(Page, CodePoint & 0xff, Page.width / 16);
    return Columns ? (Columns.Right - Columns.Left + 1) * 8 / (Page.width / 16) + 1 : MissingWidth;
}

// Widths are stored one character each: "0" plus the width in half pixels.
const Encode = (Width) => String.fromCharCode(48 + Math.round(Width * 2));
const LargeCharacters = LargeTable.map(([ Code ]) => String.fromCodePoint(Code)).join("");
const LargeWidths = LargeTable.map(([ Code, Cell ]) => Encode(MeasureLarge(Code, Cell))).join("");
let SmallTable = "";
for (let CodePoint = 0; CodePoint <= 0xffff; CodePoint++) SmallTable += Encode(MeasureSmall(CodePoint));
const Pages = [ ...Array(256).keys() ].filter((Page) => Sheet(UnicodePageName(Page << 8)) !== undefined);

const Output = `/**
 * Characters of the Bedrock client's large bitmap font with their advance
 * widths, and the advance width of every Basic Multilingual Plane character
 * in its smaller Unicode font, in font pixels including the 1-pixel gap after
 * each glyph.
 *
 * This module is auto-generated by Tool/GlyphWidths.mjs.
 *
 * @module @sorrell/ddui-image-demo/Source/GlyphWidths
 *
 * @file      GlyphWidths.js
 * @author    Gage Sorrell <gage@sorrell.sh>
 * @copyright (c) 2026 Gage Sorrell
 * @license   MIT
 */

/* eslint-disable */

/** Width of the missing-glyph box, for characters without a glyph. */
export const MissingGlyphWidth = ${MissingWidth};

/** Every character of the large font, in code point order. A line of only these is drawn in it. */
export const LargeFontCharacters = ${JSON.stringify(LargeCharacters)};

/** Large-font widths, one character for each of LargeFontCharacters: its code minus 48 is the width in half pixels. */
export const LargeFontWidths = ${JSON.stringify(LargeWidths)};

/** The Unicode font's glyph pages, by the high byte of their code points. */
export const UnicodeFontPages = ${JSON.stringify(Pages)};

/** Unicode-font widths of U+0000 to U+FFFF, one character each: its code minus 48 is the width in half pixels. */
export const UnicodeFontWidthTable = ${JSON.stringify(SmallTable)};
`;
writeFileSync(path.join(Root, "Source/GlyphWidths.js"), Output.replace(/\r?\n/gu, "\n"));
console.log(`Wrote ${LargeTable.length} large-font and ${SmallTable.length} Unicode-font widths; missing glyph ${MissingWidth}.`);
