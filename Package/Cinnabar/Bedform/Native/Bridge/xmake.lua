set_project("BedformNativeBridge")
set_xmakever("3.0.0")
set_allowedplats("windows")
set_allowedarchs("windows|x64")
add_rules("mode.release")
set_runtimes("MD")
set_toolchains("clang-cl")
add_repositories("levimc-repo https://github.com/LiteLDev/xmake-repo.git")
add_requires("levilamina 26.60.8", {configs = {target_type = "server"}})
add_requires("bedrockdata v26.60.6-server.16")
add_requires("levibuildscript 0.6.1")

target("BedformNativeBridge")
    set_kind("shared")
    set_languages("c++20")
    set_exceptions("cxx")
    add_defines("NOMINMAX", "UNICODE", "_HAS_CXX23=1", "WIN32_LEAN_AND_MEAN")
    add_cxflags("/utf-8", "-Wno-invalid-offsetof")
    add_syslinks("ws2_32", "bcrypt", "version")
    add_rules("@levibuildscript/linkrule")
    add_packages("levilamina", "bedrockdata")
    add_files("NativeBridge.cpp", "BridgeConfig.cpp", "LocalTransport.cpp")
    on_load(function ()
        import("core.base.json")
        local pins = json.loadfile(path.join(os.scriptdir(), "../../compatibility.json"))
        assert(pins.status == "aligned" and pins.bedformBdsVersion == "1.26.60.6"
            and pins.loaderVersion == "26.60.8" and pins.sdkVersion == "26.60.6-server.16"
            and pins.preLoaderVersion == "1.16.8" and pins.wireProtocol == 2225,
            "Requalify BedformNativeBridge against the new compatibility tuple.")
    end)
