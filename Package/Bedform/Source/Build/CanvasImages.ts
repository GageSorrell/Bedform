import path from "node:path";

/**
 * Project-relative virtual module; no generated file is written into consumer sources.
 *
 * @category Constant
 * @since 1.0.0
 */
export const ImageCatalog = "generated/canvas/images.ts" as const;

/**
 * Compiled image descriptors and pack-relative output bytes, ready for collision-safe staging.
 *
 * @category Model
 * @since 1.0.0
 */
export interface Compilation
{
    readonly ResourcePack: string;
    readonly Catalog: Catalog;
    readonly Images: Readonly<Record<string, ImageDescriptor>>;
    readonly Files: ReadonlyMap<string, Uint8Array>;
}

/**
 * Resolves a configuration path and rejects filesystem indirection before reading or writing it.
 * Missing final components are allowed for virtual outputs and staging.
 *
 * @throws { Error } If an existing ancestor is a link or cannot be inspected.
 *
 * @category Validation
 * @since 1.0.0
 */
async function NoLinks(file: string): Promise<void>
{
    let current = path.resolve(file);
    while (true)
    {
        try
        {
            if ((await lstat(current)).isSymbolicLink())
            {
                throw new Error(`Canvas image paths cannot contain symlinks or junctions: ${current}`);
            }
        }
        catch (error)
        {
            if ((error as NodeJS.ErrnoException).code !== "ENOENT")
            {
                throw error;
            }
        }

        const parent = path.dirname(current);
        if (parent === current)
        {
            return;
        }

        current = parent;
    }
}

/**
 * Tests path existence without hiding permission errors.
 *
 * @category Predicate
 * @since 1.0.0
 */
async function Exists(file: string): Promise<boolean>
{
    try
    {
        await lstat(file);
        return true;
    }
    catch (error)
    {
        if ((error as NodeJS.ErrnoException).code === "ENOENT")
        {
            return false;
        }

        throw error;
    }
}

/**
 * Generates a frozen, structurally typed descriptor record without runtime imports or fetches.
 * Metadata never includes absolute input paths, timestamps or build-workspace identities.
 *
 * @category Encoding
 * @since 1.0.0
 */
function Module(images: Readonly<Record<string, ImageDescriptor>>, name: string, version: string,
    license: string): string
{
    const clean = (value: string): string => value.replaceAll("*/", "* / ").replace(/[\r\n]/gu, " ");
    const members = Object.entries(images).map(([ key, image ]: [ string, ImageDescriptor ]) =>
        `    ${JSON.stringify(key)}: Object.freeze(${JSON.stringify(image, null, 4)
            .replaceAll("\n", "\n    ")} as const)`).join(",\n");
    return `/**
 * Registered Canvas images and elapsed-time vertical-flipbook metadata.
 *
 * This module is auto-generated by Source/Build/CanvasImages.ts in bedform.
 *
 * @module ${clean(name)}/generated/canvas/images
 *
 * @file      images.ts
 * @author    Gage Sorrell <gage@sorrell.sh>
 * @copyright (c) 2026 Gage Sorrell
 * @license   ${clean(license)}
 */

/* eslint-disable */

/**
 * Shared image descriptors for Intent, imperative surfaces and spatial React consumers.
 *
 * @category Constant
 * @since ${version}
 */
export const Images = Object.freeze({
${members}
});
`;
}

/**
 * Checks authored particle identifiers even when their filenames differ from generated paths.
 *
 * @throws { Error } If authored particles collide with a generated identifier or contain links.
 *
 * @category Validation
 * @since 1.0.0
 */
async function CheckParticles(directory: string, identifiers: ReadonlySet<string>): Promise<void>
{
    if (!await Exists(directory))
    {
        return;
    }

    await NoLinks(directory);
    for (const entry of await readdir(directory, { withFileTypes: true }))
    {
        const file = path.join(directory, entry.name);
        await NoLinks(file);
        if (entry.isDirectory())
        {
            await CheckParticles(file, identifiers);
        }
        else if (entry.isFile() && entry.name.endsWith(".json"))
        {
            const parsed = parseConfigFileTextToJson(file, await readFile(file, "utf8"));
            if (parsed.error)
            {
                throw new Error(`Cannot validate Canvas image conflicts in malformed particle JSON: ${file}`);
            }

            const identifier = parsed.config?.particle_effect?.description?.identifier;
            if (typeof identifier === "string" && identifiers.has(identifier))
            {
                throw new Error("Canvas image particle identifier collides with authored content: " +
                    `${identifier} in ${file}`);
            }
        }
    }
}

/**
 * Compiles resolved Canvas settings before script checking or source staging. ResourcePack selects
 * exactly one discovered destination; omission requires a sole resource pack. PNGs are decoded and
 * re-encoded as deterministic RGBA, preserving color and alpha. Frame UVs are selected by consumers
 * from elapsed feature ticks, never by particle age. Names differing only by case are rejected.
 *
 * @throws { Error } If sources, frames, identifiers, destinations or authored output conflicts are invalid.
 *
 * @category Encoding
 * @since 1.0.0
 */
export async function Compile(settings: BedformConfig.Canvas, root: string,
    resourcePacks: ReadonlyArray<string>, signal?: AbortSignal): Promise<Compilation>
{
    const resources = resourcePacks.map((file: string) => path.resolve(file));
    const selected = settings.ResourcePack === undefined ? (resources.length === 1 ? resources[0] : undefined)
        : resources.find((file: string) => path.relative(file, settings.ResourcePack!) === "");
    if (!selected)
    {
        throw new Error("Canvas.ResourcePack must select a discovered resource pack; " +
            "select it explicitly when multiple destinations exist.");
    }

    const catalog = path.join(root, ImageCatalog);
    await NoLinks(catalog);
    for (const extension of [ ".ts", ".js", ".d.ts", ".mts", ".mjs", ".d.mts" ])
    {
        if (await Exists(catalog.replace(/\.ts$/u, extension)))
        {
            throw new Error(`Canvas virtual image module collides with authored content: ${catalog}`);
        }
    }

    await NoLinks(selected);
    const images: Record<string, ImageDescriptor> = {};
    const files = new Map<string, Uint8Array>();
    const names = new Set<string>();
    for (const image of [ ...settings.Images ].sort((a: BedformConfig.CanvasImage,
        b: BedformConfig.CanvasImage) => a.Name < b.Name ? -1 : a.Name > b.Name ? 1 : 0))
    {
        signal?.throwIfAborted();
        const key = image.Name.toLowerCase();
        if (names.has(key))
        {
            throw new Error(`Duplicate Canvas image name or case-insensitive output: ${image.Name}`);
        }

        names.add(key);
        await NoLinks(image.Source);
        const input = await readFile(image.Source);
        if (input.length > 64 * 1_024 * 1_024 || input.length < 24 ||
            input.subarray(0, 8).toString("hex") !== "89504e470d0a1a0a")
        {
            throw new Error(`Canvas image ${image.Name} must be a PNG no larger than 64 MiB.`);
        }

        const width = input.readUInt32BE(16);
        const stripHeight = input.readUInt32BE(20);
        const count = image.FrameCount ?? 1;
        if (width === 0 || stripHeight === 0 || width * stripHeight > 16_777_216 || stripHeight % count !== 0)
        {
            throw new Error(`Canvas image ${image.Name} requires positive equal-height vertical frames ` +
                "within 16777216 total pixels.");
        }

        const decoded = PNG.sync.read(input);
        const texture = `textures/${settings.Namespace}/canvas/images/${key}`;
        const particle = `${settings.Namespace}:canvas_image_${key}`;
        const descriptor: ImageDescriptor = Object.freeze({ FrameCount: count,
            FrameTicks: image.FrameTicks ?? 1,
            Height: stripHeight / count,
            Id: `${settings.Namespace}:${key}`,
            Kind: "image",
            Particle: particle,
            Version: 1,
            Width: width });
        images[image.Name] = descriptor;
        files.set(texture + ".png", PNG.sync.write(decoded, { colorType: 6,
            deflateLevel: 9,
            deflateStrategy: 3,
            filterType: 4 }));
        for (const oriented of [ false, true ])
        {
            files.set(`particles/canvas/images/${key}${oriented ? OrientedSuffix : ""}.json`,
                Buffer.from(ParticleDefinition(particle, texture, width, oriented, stripHeight)));
        }
    }

    const metadataFile = path.join(root, "package.json");
    await NoLinks(metadataFile);
    const metadata = await Exists(metadataFile) ? JSON.parse(await readFile(metadataFile, "utf8")) : {};
    const version = typeof metadata.version === "string"
        ? /^\d+\.\d+\.\d+/u.exec(metadata.version)?.[0] : undefined;
    const contents = Module(images, typeof metadata.name === "string" ? metadata.name : settings.Namespace,
        version ?? "1.0.0", typeof metadata.license === "string" ? metadata.license : "MIT");
    // Preflight collisions in authored resources, then recheck exclusive writes in the stage.
    const identifiers = new Set(Object.values(images).flatMap((image: ImageDescriptor) =>
        [ image.Particle, image.Particle + OrientedSuffix ]));
    for (const resource of resources)
    {
        await NoLinks(resource);
        await CheckParticles(path.join(resource, "particles"), identifiers);
        for (const file of files.keys())
        {
            const destination = path.join(resource, file);
            await NoLinks(destination);
            if (await Exists(destination))
            {
                throw new Error(`Canvas image output collides with authored content: ${destination}`);
            }
        }
    }

    return Object.freeze({ Catalog: Object.freeze({ contents,
        file: catalog }),
    Files: files,
    Images: Object.freeze(images),
    ResourcePack: selected });
}

/**
 * Writes only into the owned staged resource pack, preserving the virtual source in the retained
 * workspace. Exclusive creation prevents overwriting authored or other generated assets.
 *
 * @throws { Error } If any generated destination already exists or cannot be written.
 *
 * @category Serialization
 * @since 1.0.0
 */
export async function Stage(compilation: Compilation, resource: string, workspace: string,
    signal?: AbortSignal): Promise<void>
{
    const files = [ ...compilation.Files,
        [ "images.ts", Buffer.from(compilation.Catalog.contents) ] ] as const;
    for (const [ file, contents ] of files)
    {
        signal?.throwIfAborted();
        if (file.split("/").some((part: string) => !part || part === "." || part === ".." ||
            part.includes("\\") || part.includes(":")))
        {
            throw new Error(`Unsafe Canvas image output path: ${file}`);
        }

        const destination = file === "images.ts" ? path.join(workspace, "canvas/images.ts")
            : path.join(resource, file);
        await NoLinks(destination);
        await mkdir(path.dirname(destination), { recursive: true });
        try
        {
            await writeFile(destination, contents, { flag: "wx" });
        }
        catch (error)
        {
            throw new Error(`Canvas image output could not be staged without overwriting: ${destination}`,
                { cause: error });
        }
    }
}
