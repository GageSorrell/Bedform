// Generates the standalone wire schema and language bindings for Bedform-8ww.13.
import { readFile, writeFile } from "node:fs/promises";
import { Actions, Events, Limits, Operations, Schema, Version } from "../../Cinnabar/Bedform/Contract/Model.mjs";

const contract = new URL("../../Cinnabar/Bedform/Contract/", import.meta.url);
const pkg = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
const since = /^\d+\.\d+\.\d+/.exec(pkg.version)[0];
const header = `/**
 * Shared v1 wire types for Cinnabar automation, capture, and installation.
 *
 * This module is auto-generated by Tool/AutomationContract.mjs.
 *
 * @module ${pkg.name}/AutomationContract.generated
 *
 * @file      AutomationContract.generated.ts
 * @author    Gage Sorrell <gage@sorrell.sh>
 * @copyright (c) 2026 Gage Sorrell
 * @license   MIT
 */

/* eslint-disable */
`;

const literal = JSON.stringify;
const upperFirst = text => text[0].toUpperCase() + text.slice(1);
const indent = (text, depth) => text.split("\n").map(line => line && "    ".repeat(depth) + line).join("\n");
const document = (name, category = "Model") => `/**
 * The automation contract's ${name.replace(/([a-z])([A-Z])/g, "$1 $2").toLowerCase()}.
 *
 * @category ${category}
 * @since ${since}
 */`;

function declaration(name, schema) {
    const nested = [];
    function typeOf(value, suffix) {
        if (value.$ref) return value.$ref.split("/").at(-1);
        if (Object.hasOwn(value, "const")) return literal(value.const);
        if (value.enum) return value.enum.map(literal).join(" | ");
        if (value.oneOf) return value.oneOf.map((part, index) => {
            const variant = part.properties?.kind?.const ?? index + 1;
            const operation = part.properties?.op?.const ?? part.properties?.event?.const ?? "";
            return typeOf(part, suffix + upperFirst(`${variant}${operation}`));
        }).join(" | ");
        if (value.type === "array") return `ReadonlyArray<${typeOf(value.items, `${suffix}Item`)}>`;
        if (value.type === "object") {
            nested.push(declaration(suffix, value));
            return `${name}.${suffix}`;
        }
        return value.type === "integer" ? "number" : value.type;
    }

    const body = schema.type === "object"
        ? `export interface ${name}\n{\n${Object.entries(schema.properties).map(([key, value]) =>
            `    readonly ${key}${schema.required.includes(key) ? "" : "?"}: ${typeOf(value, upperFirst(key))};`
        ).join("\n")}\n}`
        : `export type ${name} = ${typeOf(schema, "Alternative")};`;
    const namespace = nested.length === 0 ? "" :
        `export namespace ${name}\n{\n${indent(nested.join("\n\n"), 1)}\n}\n\n`;
    return `${namespace}${document(name)}\n${body}`;
}

// Use one source for dispatch keys and numeric defaults at every wire boundary.
const symbols = {
    Version, ...Limits,
    ...Object.fromEntries(Object.keys(Operations).map(op => [`Operation${op}`, op])),
    ...Object.fromEntries(Object.keys(Events).map(event => [`Event${event}`, event])),
    ...Object.fromEntries(Actions.map(action => [`Action${action.split("!")[1]}`, action]))
};
const rustName = name => name.replace(/([a-z])([A-Z0-9])/g, "$1_$2").toUpperCase();
const notice = "Generated by Package/ServerGameTest/Tool/AutomationContract.mjs. Do not edit.";
const actionNames = Actions.map(action => `Action${action.split("!")[1]}`);
const types = Object.entries(Schema.definitions).map(([name, schema]) => declaration(name, schema));
const ts = [header, ...Object.entries(symbols).map(([name, value]) =>
    `${document(name, "Constant")}\nexport const ${name} = ${literal(value)} as const;`), ...types].join("\n\n");
const rust = `// ${notice}\n` + Object.entries(symbols).map(([name, value]) => {
    const prefix = `pub const ${rustName(name)}: ${typeof value === "string" ? "&str" : "u32"} =`;
    const expression = `${literal(value)};`;
    return `${prefix}${prefix.length + expression.length + 1 > 100 ? "\n    " : " "}${expression}`;
}).join("\n") +
    `\npub const ACTIONS: &[&str] = &[\n${actionNames.map(name => `    ${rustName(name)},`).join("\n")}\n];`;
const goNameWidth = Math.max(...Object.keys(symbols).map(name => name.length));
const go = `// Code generated by Package/ServerGameTest/Tool/AutomationContract.mjs; DO NOT EDIT.\npackage automationcontract\n\nimport "slices"\n\nconst (\n` +
    Object.entries(symbols).map(([name, value]) => `\t${name.padEnd(goNameWidth)} = ${literal(value)}`).join("\n") +
    `\n)\n\nvar actions = [...]string{\n${actionNames.map(name => `\t${name},`).join("\n")}\n}\n\n` +
    "// IsAction recognizes the serialized action registry keys.\nfunc IsAction(value string) bool {\n\treturn slices.Contains(actions[:], value)\n}";
const cpp = `// ${notice}\n#pragma once\n\n#include <array>\n#include <cstdint>\n#include <string_view>\n\nnamespace bedform::automation {\n` +
    Object.entries(symbols).map(([name, value]) =>
        `inline constexpr ${typeof value === "string" ? "std::string_view" : "std::uint32_t"} ${name} = ${literal(value)};`
    ).join("\n") + `\ninline constexpr auto Actions = std::array{\n${actionNames.map(name => `    ${name},`).join("\n")}\n};\n}`;
const outputs = [
    [new URL("automation-v1.schema.json", contract), JSON.stringify(Schema, null, 2)],
    [new URL("automation_contract.rs", contract), rust],
    [new URL("AutomationContract.h", contract), cpp],
    [new URL("../../Cinnabar/core/internal/automationcontract/contract.go", import.meta.url), go],
    [new URL("../Source/AutomationContract.generated.ts", import.meta.url), ts]
];

const check = process.argv.includes("--check");
for (const [file, content] of outputs) {
    if (!check) {
        await writeFile(file, `${content}\n`);
        continue;
    }
    const current = await readFile(file, "utf8");
    if (current.replaceAll("\r\n", "\n") !== `${content}\n`) {
        console.error(`Stale generated contract: ${file.pathname}`);
        process.exitCode = 1;
    }
}
